import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const modelPath = path.join(here, '..', 'model', 'scenarios.json');
const outputPath = path.join(here, 'scenarios.mjs');

const expectedIds = [
  ...Array.from({ length: 9 }, (_, index) => `L${String(index + 1).padStart(2, '0')}`),
  ...Array.from({ length: 10 }, (_, index) => `D${String(index + 1).padStart(2, '0')}`),
  ...Array.from({ length: 8 }, (_, index) => `C${String(index + 1).padStart(2, '0')}`),
  ...Array.from({ length: 14 }, (_, index) => `R${String(index + 1).padStart(2, '0')}`),
];

function assertValidModel(model) {
  if (model.schemaVersion !== 1 || model.canonical !== true) {
    throw new Error('model/scenarios.json must declare schemaVersion 1 and canonical=true.');
  }

  if (!Array.isArray(model.scenarios)) {
    throw new Error('model/scenarios.json must contain a scenarios array.');
  }

  const ids = model.scenarios.map((scenario) => scenario.id);
  const uniqueIds = new Set(ids);
  const missing = expectedIds.filter((id) => !uniqueIds.has(id));
  const extra = ids.filter((id) => !expectedIds.includes(id));
  if (ids.length !== expectedIds.length || uniqueIds.size !== ids.length || missing.length || extra.length) {
    throw new Error(`Expected the 41 US-025 state IDs in order; missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'}.`);
  }

  if (ids.some((id, index) => id !== expectedIds[index])) {
    throw new Error('Scenario definitions must retain the canonical L01-L09, D01-D10, C01-C08, R01-R14 order.');
  }

  for (const scenario of model.scenarios) {
    if (!scenario.title || !scenario.trigger || !scenario.expected || !scenario.action || !Array.isArray(scenario.next)) {
      throw new Error(`${scenario.id} is missing its title, trigger, expected behavior, action, or next-state list.`);
    }
  }

  const requiredFixtures = ['standard', 'long', 'optional', 'completed', 'cancelled', 'rateLimit'];
  for (const name of requiredFixtures) {
    if (!model.fixtures?.[name]) throw new Error(`Missing content fixture: ${name}.`);
  }

  for (const name of requiredFixtures.slice(0, 5)) {
    const fixture = model.fixtures[name];
    if (fixture.jobId !== 41 || !fixture.status || typeof fixture.offeredPrice !== 'string' || !Array.isArray(fixture.surveys)) {
      throw new Error(`Fixture ${name} must retain the mock Job #41 identity, status, decimal-string price, and survey names.`);
    }
  }
}

function renderModule(model) {
  const scenarios = JSON.stringify(model.scenarios, null, 2);
  const fixtures = JSON.stringify(model.fixtures, null, 2);
  return [
    '// Generated by build.mjs from ../model/scenarios.json. Do not edit by hand.',
    `export const MODEL_SOURCE = ${JSON.stringify(model.source)};`,
    `export const SCENARIOS = ${scenarios};`,
    'export const SCENARIO_BY_ID = Object.freeze(Object.fromEntries(SCENARIOS.map((scenario) => [scenario.id, scenario])));',
    `export const FIXTURES = ${fixtures};`,
    'export const SCENARIO_IDS = Object.freeze(SCENARIOS.map((scenario) => scenario.id));',
    '',
  ].join('\n');
}

const model = JSON.parse(await readFile(modelPath, 'utf8'));
assertValidModel(model);
const output = renderModule(model);

if (process.argv.includes('--check')) {
  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch {
    throw new Error('demo/scenarios.mjs is missing. Run `node "UX UI/US-025/demo/build.mjs"` to generate it.');
  }
  if (existing !== output) {
    throw new Error('demo/scenarios.mjs is stale. Run `node "UX UI/US-025/demo/build.mjs"` to regenerate it.');
  }
  console.log(`Scenario module is current (${model.scenarios.length} states, ${Object.keys(model.fixtures).length} fixtures).`);
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Generated demo/scenarios.mjs (${model.scenarios.length} states, ${Object.keys(model.fixtures).length} fixtures).`);
}
