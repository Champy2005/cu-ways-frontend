import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const modelPath = path.join(here, '..', 'model', 'scenarios.json');
const legacyPath = path.join(here, '..', 'design', 'manifest.json');
const outputPath = path.join(here, 'scenarios.mjs');
const expectedIds = [
  'A01', 'A02', 'A03', 'A04', 'A05', 'A06',
  'B01', 'B02', 'B03', 'B04', 'C01', 'C02', 'C03', 'C04',
];

function assertValidModel(model, legacy) {
  if (model.schemaVersion !== 1 || model.canonical !== true || model.story !== 'US-026') {
    throw new Error('model/scenarios.json must declare schemaVersion 1, canonical=true, and story US-026.');
  }
  if (!Array.isArray(model.scenarios) || !Array.isArray(model.criteria)) {
    throw new Error('The canonical model must include scenarios and acceptance criteria arrays.');
  }
  const ids = model.scenarios.map((scenario) => scenario.id);
  if (ids.length !== expectedIds.length || ids.some((id, index) => id !== expectedIds[index])) {
    throw new Error(`Expected the 14 US-026 scenario IDs in order: ${expectedIds.join(', ')}.`);
  }
  if (JSON.stringify(legacy.states.map((state) => state.id).sort()) !== JSON.stringify([...expectedIds].sort())) {
    throw new Error('The canonical model must cover every state in the retained US-026 source design manifest.');
  }
  const known = new Set(ids);
  for (const scenario of model.scenarios) {
    if (!scenario.group || !scenario.title || !scenario.trigger || !scenario.expected || !scenario.action || !Array.isArray(scenario.next)) {
      throw new Error(`${scenario.id} is missing its group, title, trigger, expected behavior, action, or next-state list.`);
    }
    for (const next of scenario.next) {
      if (!known.has(next)) throw new Error(`${scenario.id} points to unknown state ${next}.`);
    }
  }
  for (const criterion of model.criteria) {
    if (!criterion.id || !criterion.source || !criterion.requirement) {
      throw new Error('Every acceptance criterion needs an id, source, and requirement.');
    }
  }
  for (const name of ['standard', 'long']) {
    const fixture = model.fixtures?.[name];
    if (fixture?.jobId !== 41 || !fixture.jobTitle || fixture.jobStatus !== 'In Progress' || !fixture.initialUrl || !fixture.secondUrl) {
      throw new Error(`Fixture ${name} must preserve a complete In Progress job and proof URL pair.`);
    }
  }
}

function renderModule(model) {
  return [
    '// Generated by build.mjs from ../model/scenarios.json. Do not edit by hand.',
    `export const SOURCE = ${JSON.stringify(model.source)};`,
    `export const CRITERIA = ${JSON.stringify(model.criteria, null, 2)};`,
    `export const FIXTURES = ${JSON.stringify(model.fixtures, null, 2)};`,
    `export const SCENARIOS = ${JSON.stringify(model.scenarios, null, 2)};`,
    'export const SCENARIO_IDS = Object.freeze(SCENARIOS.map(({ id }) => id));',
    'export const SCENARIO_BY_ID = Object.freeze(Object.fromEntries(SCENARIOS.map((scenario) => [scenario.id, scenario])));',
    '',
  ].join('\n');
}

const [modelText, legacyText] = await Promise.all([
  readFile(modelPath, 'utf8'),
  readFile(legacyPath, 'utf8'),
]);
const model = JSON.parse(modelText);
const legacy = JSON.parse(legacyText);
assertValidModel(model, legacy);
const output = renderModule(model);

if (process.argv.includes('--check')) {
  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch {
    throw new Error('demo/scenarios.mjs is missing. Run `node "UX UI/US-026/demo/build.mjs"` to generate it.');
  }
  if (existing !== output) {
    throw new Error('demo/scenarios.mjs is stale. Run `node "UX UI/US-026/demo/build.mjs"` to regenerate it.');
  }
  console.log(`US-026 scenario module is current (${model.scenarios.length} states, ${model.criteria.length} acceptance criteria).`);
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Generated US-026 scenario module (${model.scenarios.length} states, ${model.criteria.length} acceptance criteria).`);
}
