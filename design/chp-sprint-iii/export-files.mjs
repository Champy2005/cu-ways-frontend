export function handoffFiles(root) {
  for (const file of files) {
    const target = path.resolve(root, file), relative = path.relative(root, target);
    if (relative.startsWith('..') || path.isAbsolute(relative) || !fs.lstatSync(target).isFile()) throw Error('Invalid handoff source: ' + file);
  }
  return [...files];
}
